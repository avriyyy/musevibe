import type { Platform, Timeline } from "./project-options";
import type { DesignSystemRef, PlannedPage } from "./design-system";
import type { WizardAnswerValue, WizardQuestion } from "./wizard";
import type { PlanningRun } from "./planning-run";

export type TaskStatus = "todo" | "doing" | "review" | "blocked" | "done" | "cancelled";

export interface ProjectAnswer {
  qid: string;
  question: string;
  answer: string;
  values?: WizardAnswerValue;
}

export interface ProjectDoc {
  id: string;
  /** One of the six plan kinds, or "note" for a custom supporting document. */
  kind: string;
  title: string;
  markdown: string;
  updatedAt: string;
  /** Provenance of stored text. `local` is legacy-only for plan documents and
   *  is cleared instead of displayed as a generated document. */
  source?: "ai" | "local" | "edited";
}

export interface Project {
  id: string;
  name: string;
  /** Customer-facing brand used on generated website screens; separate from the workspace label. */
  brandName?: string;
  idea: string;
  createdAt: string;
  lastOpenedAt?: string;
  /** Draft means the setup wizard is not finished yet and can be resumed. */
  status?: "draft" | "ready";
  /** Last wizard step reached, so an unfinished draft resumes where it stopped. */
  wizardStep?: number;
  platform?: Platform;
  timeline?: Timeline;
  /** Framework value from the stack picker, e.g. "nextjs". */
  framework?: string;
  /** Chat model chosen in the composer, reused by the wizard generators. */
  model?: string;
  answers?: ProjectAnswer[];
  /** Cached questionnaire so a refresh reuses it instead of calling the AI again. */
  questions?: WizardQuestion[];
  questionSource?: "ai" | "local";
  /** Image URL or data URL for the project logo. Absent means initials. */
  logoUrl?: string;
  /** Provenance of the current mark. Missing means legacy or unknown. */
  logoOrigin?: "ai" | "upload";
  /** Strip the image background after generation or upload. Defaults to on. */
  logoRemoveBg?: boolean;
  /** Logo image format: raster from the image model, vector from the text model. */
  logoFormat?: "png" | "svg";
  /** Replaced marks, newest last, so a new generation never loses the old one. */
  logoHistory?: string[];
  /** User-written logo direction, persisted across wizard refresh/resume. */
  logoBrief?: string;
  /** Chosen design system: template, uploaded design.md, or converted link. */
  designSystem?: DesignSystemRef;
  /** Planned prototype pages in build order; files hold the generated HTML. */
  pagePlan?: PlannedPage[];
  /** Provenance of the current page suggestions. */
  pagePlanSource?: "ai" | "local";
  /** Lets first-run plan generation resume after a refresh without rewriting saved work. */
  planningPrep?: "in-progress" | "complete";
  /** Per-unit memory for the current first-run pass, so a refresh retries
   *  exactly the units that never settled. */
  planningRun?: PlanningRun;
}

export interface Prd {
  problem: string;
  users: string;
  features: string[];
  scopeOut: string[];
  raw: string;
}

export interface Task {
  id: string;
  title: string;
  status: TaskStatus;
  linkedScreenId?: string;
  notes?: string;
}

export interface Screen {
  id: string;
  name: string;
  canvasJson: string; // Custom canvas shapes JSON (stringified)
  components: string[];
}

export interface CodeFile {
  id: string;
  path: string;
  content: string;
  language: string;
  /** Generated by the model, or drawn locally as a clearly labelled draft. */
  source?: "ai" | "local";
  updatedAt?: string;
}

/** Atomic JSONB representation persisted for one signed-in user's project. */
export interface CloudWorkspaceSnapshot {
  version: 1;
  project: Project;
  prd: string;
  tasks: Task[];
  screens: Screen[];
  files: CodeFile[];
  docs: ProjectDoc[];
}

/** Server revision is `updated_at` from Neon and changes after every successful write. */
export interface CloudWorkspaceRecord {
  snapshot: CloudWorkspaceSnapshot;
  revision: string;
}
